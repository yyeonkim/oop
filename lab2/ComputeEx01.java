public class ComputeEx01 {
    public static void main(String[] args) {
        int a = 100, b = 25;
        int result;

        // Add
        result = a + b;
        System.out.printf("%d + %d = %d\n", a, b, result);

        // Substract
        result = a - b;
        System.out.printf("%d - %d = %d\n", a, b, result);

        // Multiply
        result = a * b;
        System.out.printf("%d * %d = %d\n", a, b, result);

        // Divide
        result = a / b;
        System.out.printf("%d / %d = %d\n", a, b, result);
    }
}